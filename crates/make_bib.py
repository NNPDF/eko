"""Parse bibtex file(s) to rust crate(s)."""

import argparse
import datetime
import pathlib
import re
import sys

import bibtexparser

HERE = pathlib.Path(__file__).parent

# File constants
BIB_FILE = "refs.bib"
RS_FILE = "bib.rs"

# A single entry
ENTRY = """#[allow(non_snake_case)]
/// {title}
///
/// {author}
///
/// {publication}
///
/// {eprint}
///
/// {doi}"""
# Combine publication information
PUB = """Published in: {journal} {volume} ({year}), {pages}"""
PHD = """Published as PhD thesis at {school} ({year})"""


def sanitize(t: str) -> str:
    """Reformat for HTML."""
    # Shrink whitespace to one.
    t = re.sub(r"\n\s+", " ", t)
    # Recover some TeX
    t = t.replace(r"\textendash{}", "-").replace(r"\'a", "á")
    # Remove curly brackets
    t = re.sub(r"^\{(.+)\}$", r"\1", t)
    return t


def generate_bib_module(bib_path: pathlib.Path) -> str:
    """Generate Rust module contents from a bibtex file."""
    now = datetime.datetime.now().isoformat()
    out = f"//! List of References (autogenerated on {now}).\n\n"

    # Parse
    bib_str = bib_path.read_text("utf8")
    bib_database = bibtexparser.parse_string(bib_str)

    # iterate all elements
    for el in bib_database.entries:
        title = sanitize(el.fields_dict["title"].value)
        author = sanitize(el.fields_dict["author"].value)
        # build publication
        if el.entry_type == "phdthesis":
            publication = PHD.format(
                school=el.fields_dict["school"].value,
                year=el.fields_dict["year"].value,
            )
        else:
            publication = PUB.format(
                journal=el.fields_dict["journal"].value,
                volume=el.fields_dict["volume"].value,
                year=el.fields_dict["year"].value,
                pages=el.fields_dict["pages"].value,
            )
        # arxiv link?
        eprint = ""
        if (
            "eprint" in el.fields_dict
            and "archivePrefix" in el.fields_dict
            and el.fields_dict["archivePrefix"].value == "arXiv"
        ):
            ar = el.fields_dict["eprint"].value
            eprint = f"e-Print: [{ar}](https://arxiv.org/abs/{ar})"
        # DOI link?
        doi = ""
        if "doi" in el.fields_dict:
            ddoi = el.fields_dict["doi"].value
            url = ddoi if "http" in ddoi else f"https:dx.doi.org/{ddoi}"
            doi = f"DOI: [{ddoi}]({url})"
        # build docstring
        doc = ENTRY.format(
            title=title,
            author=author,
            publication=publication,
            eprint=eprint,
            doi=doi,
        )
        out += doc + "\n" + f"pub fn {el.key}() {{}} \n\n"

    out = re.sub(r" +\n", "\n", out.strip()) + "\n"
    return out


def main():
    """Main entrypoint."""
    parser = argparse.ArgumentParser(description="Parse bibtex file(s) to rust crate(s)")
    parser.add_argument(
        "crate",
        nargs="?",
        default=None,
        help=f"Specific crate to process (e.g. ekore, eko). If omitted, processes all crates with {BIB_FILE}.",
    )
    parser.add_argument(
        "--stdout",
        action="store_true",
        help=f"Print generated module to stdout instead of writing to src/{RS_FILE}",
    )
    args = parser.parse_args()

    # Discover target crates
    if args.crate:
        crate_dir = HERE / args.crate
        if not crate_dir.is_dir():
            crate_dir = pathlib.Path(args.crate)
        if not (crate_dir / BIB_FILE).is_file():
            print(f"Error: {crate_dir / BIB_FILE} not found", file=sys.stderr)
            sys.exit(1)
        targets = [crate_dir]
    else:
        # Find all crates with refs.bib
        targets = sorted([d for d in HERE.iterdir() if d.is_dir() and (d / BIB_FILE).is_file()])

    if not targets:
        print(f"No crates with {BIB_FILE} found.", file=sys.stderr)
        sys.exit(1)

    # iterate all selected crates
    for target in targets:
        bib_file = target / BIB_FILE
        generated = generate_bib_module(bib_file)
        if args.stdout:
            print(generated)
        else:
            output_file = target / "src" / RS_FILE
            output_file.parent.mkdir(parents=True, exist_ok=True)
            output_file.write_text(generated, encoding="utf-8", newline="\n")
            print(f"Generated {output_file} from {bib_file}")


if __name__ == "__main__":
    main()
